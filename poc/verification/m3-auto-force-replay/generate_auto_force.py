#!/usr/bin/env python3
"""Generate or reproduce the offline M3 auto-Force replay."""

import argparse
import json
from pathlib import Path

from sample import sample_projection


PAGE_DIR = Path(__file__).resolve().parents[2] / "web" / "m1-gfr-replay"


def render(data):
    encoded = json.dumps(data, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    encoded = encoded.replace("<", "\\u003c").replace(">", "\\u003e").replace("&", "\\u0026")
    return ((PAGE_DIR / "auto-force-template.html").read_text()
            .replace("/* INLINE_CSS */", (PAGE_DIR / "replay.css").read_text() + "\n" + (PAGE_DIR / "auto-force.css").read_text())
            .replace("/* INLINE_JS */", (PAGE_DIR / "auto-force.js").read_text())
            .replace("INLINE_JSON", encoded)).encode("utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--sample", action="store_true", help="explicitly labeled contract sample")
    mode.add_argument("--bundle", type=Path, help="completed AF01 evidence directory")
    parser.add_argument("--independent", type=Path, help="independent AF01 checker output directory")
    parser.add_argument("--output", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if not args.sample and args.independent is None:
        parser.error("formal mode requires --independent")
    if args.sample and args.independent is not None:
        parser.error("--sample does not accept --independent")
    output = args.output or PAGE_DIR / ("auto-force-sample.html" if args.sample else "auto-force.html")
    try:
        if args.sample:
            if output.name == "auto-force.html":
                raise ValueError("sample output must be separate from auto-force.html")
            data = sample_projection()
        else:
            from projection import formal_projection
            data = formal_projection(args.bundle, args.independent)
        html = render(data)
        if args.check:
            if output.read_bytes() != html:
                raise ValueError(f"{output}: replay differs from generated bytes")
        else:
            output.write_bytes(html)
    except (OSError, ValueError, TypeError, KeyError, IndexError, StopIteration) as error:
        parser.exit(1, f"M3 replay: {error}\n")
    print(f"PASS: {data['mode']} M3 replay, {len(data['events'])} frames · {output}")


if __name__ == "__main__":
    main()
