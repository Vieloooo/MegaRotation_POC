#!/usr/bin/env python3
"""Generate the self-contained M4 D/RESUME offline replay."""

import argparse
import json
import os
from pathlib import Path
from tempfile import NamedTemporaryFile

from evidence import load_formal
from model import project
from sample import sample_tape


PAGE = Path(__file__).resolve().parents[2] / "web" / "m1-gfr-replay"
BASELINE = "b404818e18be62663e84a7fa580b151c686ad951"


def render(page):
    payload = json.dumps(page, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    payload = payload.replace("<", "\\u003c").replace(">", "\\u003e").replace("&", "\\u0026")
    if PAGE.is_dir():
        assets = PAGE
    else:
        assets = Path(__file__).resolve().parents[1] / "web"
    read = lambda name: (assets / name).read_text(encoding="utf-8")
    return (read("resume-template.html").replace("/* INLINE_CSS */", read("replay.css") + "\n" + read("resume.css"))
            .replace("/* INLINE_JS */", read("resume.js")).replace("INLINE_JSON", payload)).encode("utf-8")


def publish(output, html):
    pending = None
    try:
        with NamedTemporaryFile(dir=output.parent, prefix=".m4-replay-", delete=False) as stream:
            pending = Path(stream.name)
            stream.write(html)
        pending.chmod(0o644)
        os.replace(pending, output)
    finally:
        if pending is not None:
            pending.unlink(missing_ok=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--sample", action="store_true")
    mode.add_argument("--bundle", type=Path)
    parser.add_argument("--independent", type=Path)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.sample == (args.independent is not None):
        parser.error("provide --independent only with --bundle")
    output = args.output or PAGE / ("resume-sample.html" if args.sample else "resume.html")
    try:
        if args.sample:
            if output.name == "resume.html" or output.resolve().name == "resume.html":
                raise ValueError("sample target must use a separate filename")
            page = project(sample_tape(), "sample", {"baseline": BASELINE,
                           "contract": "M4-D-RESUME-1 · a5ed3a8 · DR01 主路径计划",
                           "events": "合成虚拟轨迹。WAIT、区块标识、局部时点与示例签名材料均为样本设定。"})
        else:
            page = load_formal(args.bundle, args.independent)
        html = render(page)
        if args.check:
            if output.read_bytes() != html:
                raise ValueError(f"{output} does not match regenerated bytes")
        else:
            publish(output, html)
    except (OSError, ValueError, TypeError, KeyError, IndexError, OverflowError) as exc:
        parser.exit(1, f"M4 replay: {exc}\n")
    print(f"PASS: {page['mode']} M4 replay, {len(page['frames'])} frames · {output}")


if __name__ == "__main__":
    main()
